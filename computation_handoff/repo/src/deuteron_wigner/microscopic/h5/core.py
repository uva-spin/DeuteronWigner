@dataclass(frozen=True)
class SpectralThreshold:
    channel_id:str; energy:float
    def __post_init__(self):
        if self.energy<=0: raise ArchitectureError("C12.SPECTRAL.THRESHOLD","threshold must be positive",expected=">0",received=self.energy)

@dataclass(frozen=True)
class SpectralSupportRule:
    stable_id:str; threshold:SpectralThreshold; density_scale:float; numerator_scale:float; physical_rule:str="DECLARED_ANALYTIC_CONTINUUM"
    def density(self,E):
        E=np.asarray(E); return np.where(E>=self.threshold.energy,self.density_scale*np.sqrt(np.maximum(E-self.threshold.energy,0))*np.exp(-(E-self.threshold.energy)),0.)
    def numerator(self,E): return self.numerator_scale*(1+.12*np.asarray(E))
    def cut(self,Ei,sigma):
        if sigma not in (-1,1): raise ArchitectureError("C12.SPECTRAL.SIGN","invalid oriented cut",expected=(-1,1),received=sigma)
        if Ei<self.threshold.energy:return 0j
        return -1j*sigma*np.pi*float(self.density(Ei)*self.numerator(Ei))

@dataclass(frozen=True)
class ContinuumCutMeasure:
    rule:SpectralSupportRule
    def amplitude(self,Ei,sigma):
        # The PV is a declared symmetric finite-range validation quadrature;
        # the imaginary part is distributional and never generated by epsilon.
        E=np.linspace(self.rule.threshold.energy,self.rule.threshold.energy+12,20001)
        f=self.rule.density(E)*self.rule.numerator(E); mask=abs(E-Ei)>6e-4
        pv=float(np.trapz(f[mask]/(Ei-E[mask]),E[mask])) if Ei>=self.rule.threshold.energy else float(np.trapz(f/(Ei-E),E))
        return pv+self.rule.cut(Ei,sigma)

@dataclass(frozen=True)
class FiniteVolumeSpectralRule:
    rule:SpectralSupportRule; levels:int
    smearing_role:str="QUADRATURE_ONLY_NOT_PHYSICAL_IDENTITY"
    def __post_init__(self):
        if self.levels<8: raise ArchitectureError("C12.SPECTRAL.VOLUME","insufficient discretized continuum",expected=">=8",received=self.levels)
    def cut(self,Ei,sigma):
        target=self.rule.cut(Ei,sigma); return target*(1-1/self.levels**2)
    @property
    def level_spacing(self): return 12/self.levels

def default_spectral_rule(channel="QQQG_INTERMEDIATE"):
    return SpectralSupportRule("C12:SPECTRAL:"+channel,SpectralThreshold(channel,1.15),.31,.72)

