def build_h5_bundle(plan=None,solver="EXACT_VECTOR",bond_fraction=1.):
    plan=plan or h4_plans()[0]; E=MicroscopicOverlapKernel();K=H4WilsonKernel();rows=[]
    for t in TARGETS:
      for s in SPECIES:
        p=E.matrix(plan,t,s,solver=solver); strength=.44*bond_fraction
        rows.append(K.apply(p,oam_strength=strength,solver=solver))
    return tuple(rows)
