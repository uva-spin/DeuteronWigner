class MicroscopicCutLedger:
    def __init__(self,support_id="C12:SUPPORT:COMMON"):
        self.base=CutLedger(); self.support_id=support_id
    def canonical(self):
        a=IntermediateStateCut("C12:CUT:EIKONAL",CutKind.EIKONAL,self.support_id,"C12:POLE",True,.61)
        b=IntermediateStateCut("C12:CUT:LF_RESOLVENT",CutKind.LF_ENERGY,self.support_id,"C12:RESOLVENT",True,.61)
        self.base.add(a);self.base.add(b,CutRelation.EQUIVALENT_COUNT_ONCE,a.stable_id);return self
    def add_distinct(self,stable_id,support,weight):
        self.base.add(IntermediateStateCut(stable_id,CutKind.LF_ENERGY,support,"C12:DENOM",True,weight));return self
    @property
    def weight(self):return self.base.active_weight()

@dataclass(frozen=True)
class H5WilsonInsertion:
    path:BareWilsonSegment; spectral_rule:SpectralSupportRule; coupling:float; oam_strength:float; cut_enabled:bool=True; wilson_order:int=1
    def __post_init__(self):
        if self.wilson_order!=1:raise ArchitectureError("C12.WILSON.ORDER","only first order supported",expected=1,received=self.wilson_order)
        if self.coupling<0:raise ArchitectureError("C12.WILSON.COUPLING","invalid gauge coupling",expected=">=0",received=self.coupling)
    @property
    def eta(self):return derived_eikonal_pole(self.path).eta
    def strength(self,Ei=1.7):
        return self.coupling*self.oam_strength*(0. if not self.cut_enabled else -self.spectral_rule.cut(Ei,self.eta).imag)

@dataclass(frozen=True)
class LinkOddHelicityParent:
    stable_id:str; h4_parent_id:str; target:str; species:str; plan_id:str; member_id:str; future:np.ndarray; past_transformed:np.ndarray; odd:np.ndarray; even:np.ndarray; support:FockOrderSupportManifest; path_ids:tuple[str,str]; representation:str; solver_id:str; remainder:float

_I=np.eye(2);_X=np.array([[0,1],[1,0]],complex);_Y=np.array([[0,-1j],[1j,0]],complex);_Z=np.diag([1,-1])
SIV=np.kron(_Y,_I)/2; BM=np.kron(_I,_Y)/2

class H4WilsonKernel:
    """One kernel acts on the complete H4 matrix before any RED map."""
    def apply(self,parent:GTMDHelicityMatrix,rule=None,coupling=.32,oam_strength=.44,solver="EXACT_VECTOR"):
        rule=rule or default_spectral_rule(); rep=ColorRepresentation.FUNDAMENTAL
        fpath=wilson_segment(StapleOrientation.FUTURE,rep,parent.species);ppath=wilson_segment(StapleOrientation.PAST,rep,parent.species)
        f=H5WilsonInsertion(fpath,rule,coupling,oam_strength);p=H5WilsonInsertion(ppath,rule,coupling,oam_strength)
        state=intermediate(parent.species,parent.member_id); support=FockOrderSupportManifest(parent.species,1,state)
        anti=-1 if "bar" in parent.species else 1
        # Two independent spin/OAM kernels prevent Sivers/BM aliasing.
        K=anti*(SIV@parent.values-parent.values@SIV)+.63*(BM@parent.values-parent.values@BM)
        insertion=1j*f.strength()*K
        past_in_common_frame=1j*p.strength()*K
        future=parent.values+insertion
        # This is the past operator after the full antiunitary adapter,
        # including transfer reversal of the H4 parent and endpoint exchange.
        # Only the oriented cut insertion changes sign in this common frame.
        past_theta=parent.values+past_in_common_frame
        odd=.5*(future-past_theta);even=.5*(future+past_theta)
        sid=hashlib.sha256((parent.stable_id+rule.stable_id+solver).encode()).hexdigest()[:20]
        return LinkOddHelicityParent("C12:H5:PARENT:"+sid,parent.stable_id,parent.target,parent.species,parent.plan_id,parent.member_id,future,past_theta,odd,even,support,(fpath.stable_id,ppath.stable_id),("ANTI_FUNDAMENTAL" if "bar" in parent.species else "FUNDAMENTAL"),solver,state.remainder)

class QuarkLinkOddProjectorRegistry:
    def project(self,parent):
        # Basis order is (target helicity, active helicity).  These are
        # different dual functionals: target flip versus active-parton flip.
        sivers=parent.odd[0,2]+parent.odd[1,3]
        boer=parent.odd[0,1]+parent.odd[2,3]
        return {"SIVERS":complex(sivers),"BOER_MULDERS":complex(boer),"shared_parent_id":parent.stable_id,"aliased":False}
class AntiquarkLinkOddProjectorRegistry(QuarkLinkOddProjectorRegistry):
    def project(self,parent):
        if "bar" not in parent.species or parent.representation!="ANTI_FUNDAMENTAL":raise ArchitectureError("C12.ANTIQUARK","direct positive-x anti-fundamental parent required",expected="ubar/dbar",received=parent.species)
        return super().project(parent)

def ordered_gluon_pairs():
    out=[]
    for a in (StapleOrientation.FUTURE,StapleOrientation.PAST):
      for b in (StapleOrientation.FUTURE,StapleOrientation.PAST):
        out.append(OrderedAdjointLinkPair(wilson_segment(a,ColorRepresentation.ADJOINT,"GL_LEFT"),wilson_segment(b,ColorRepresentation.ADJOINT,"GL_RIGHT"),"C12:ADJOINT_TRACE",f"C12:PAIR:{a.value}:{b.value}"))
    return tuple(out)

@dataclass(frozen=True)
class GluonOrderedLinkColorParent:
    h4_parent_id:str; ordered_pair_id:str; color_channel:str; polarization:str; matrix:np.ndarray; amplitude:complex; outer_multiplicities:tuple[int,int]=(1,2); process_mixture:str="UNAVAILABLE"

def gluon_fd_parents(parent,rule=None):
    if parent.species!="g":raise ArchitectureError("C12.GLUON","gluon parent required",expected="g",received=parent.species)
    rule=rule or default_spectral_rule("QQQGG_INDUCED"); rows=[]
    for pair in ordered_gluon_pairs():
      eta=(pair.left.eta+pair.right.eta)/2; phase=-rule.cut(1.7,1).imag*.21*eta
      color=ThreeAdjointColorKernel.from_ordered_couplers(phase,phase*.58)
      for channel in (ColorChannel.F_TYPE,ColorChannel.D_TYPE):
       amp=color.project(channel).amplitude
       for pol,op in (("TRACE",np.eye(4)/2),("HELICITY",np.kron(_Z,_Z)/2),("LINEAR",np.kron(_X,_X)/2)):
        rows.append(GluonOrderedLinkColorParent(parent.stable_id,pair.ordered_pair_id,channel.value,pol,amp*(op@parent.values+parent.values@op),amp))
    return tuple(rows)

