@dataclass(frozen=True)
class MicroscopicIntermediateState:
    stable_id:str; initial_member:str; sector:str; threshold_id:str; active_attachment:str; spectator_attachment:str; color_kernel:str; helicity_kernel:str; oam_interference:str; support:FockSupport; remainder:float

def intermediate(species,member):
    if species in ("u","d"): support,rem=FockSupport.EXPLICIT,0.
    elif species=="g": support,rem=FockSupport.INDUCED,.026
    else: support,rem=FockSupport.INDUCED,.018 if species=="ubar" else .021
    sector="QQQG" if species in ("u","d","g") else ("QQQUUBAR" if species=="ubar" else "QQQDDBAR")
    return MicroscopicIntermediateState(f"C12:STATE:{species}",member,sector,"C12:THRESHOLD:1.15","ACTIVE_EIKONAL","SPECTATOR_DELTA","C5_C6_CANONICAL","FULL_4X4","DELTA_LZ_1",support,rem)

